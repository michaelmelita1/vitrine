#!/bin/sh
# build-stamp.sh <out.m>: writes which build this is, shown beside the version in Mod Settings. It is the
# commit, and for a build with uncommitted changes a + and the time it was built, so every test build can
# be told apart. The file is rewritten only when the stamp changes, so only it compiles again.
out=$1
stamp=$(git rev-parse --short HEAD 2>/dev/null || echo unknown)
if [ -n "$(git status --porcelain --untracked-files=no 2>/dev/null | head -1)" ]; then
    stamp="$stamp+${SG_BUILD_TIME:-$(date +%m%d.%H%M)}"
fi
text="// Generated by scripts/build-stamp.sh.
const char *SGBuildStamp(void) { return \"$stamp\"; }"
[ "$(cat "$out" 2>/dev/null)" = "$text" ] || printf '%s\n' "$text" > "$out"
